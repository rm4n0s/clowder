// Command gencodecss writes internal/web/static/code.css, the stylesheet of
// the code blocks that internal/markdown renders: the block itself and the
// colours of the hl- classes of the highlighted tokens, for a light and a dark
// palette. It is run by go generate (see internal/markdown/code.go) and its
// output is committed; a test fails when the committed file is out of date.
//
// The palettes are the chroma styles named by lightStyle and darkStyle, and the
// colours of the block itself are the constants below. Step 21.1 replaces
// them with the tokens of the new look.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/alecthomas/chroma/v2"
	"github.com/alecthomas/chroma/v2/styles"
	"github.com/rm4n0s/errors"

	"github.com/rm4n0s/clowder/internal/markdown"
)

const (
	// lightStyle is the chroma style of the light palette.
	lightStyle = "github"
	// darkStyle is the chroma style of the dark palette.
	darkStyle = "github-dark"
)

// palette is the colours of a code block that do not depend on the tokens.
type palette struct {
	bg, fg, border string
}

var (
	lightPalette = palette{bg: "#f6f8fa", fg: "#1f2328", border: "#d0d7de"}
	darkPalette  = palette{bg: "#161b22", fg: "#e6edf3", border: "#30363d"}
)

// The selectors that make the dark palette apply, as in app.css: when the
// person chose Dark in the settings, and when the system asks for dark unless
// the person chose Light.
const (
	darkSelector  = `:root[data-theme="dark"]`
	systemDarkSel = `:root:not([data-theme="light"])`
	darkMedia     = `@media (prefers-color-scheme: dark)`
)

func main() {
	out := flag.String("o", "", "the file to write")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "gencodecss: -o is required")
		os.Exit(2)
	}
	css, err := generate(lightStyle, darkStyle)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gencodecss:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, css, 0o644); err != nil { //nolint:gosec // a stylesheet that is committed
		fmt.Fprintln(os.Stderr, "gencodecss:", err)
		os.Exit(1)
	}
}

// generate returns the content of code.css, made from the chroma styles with
// the names lightStyle and darkStyle.
func generate(lightStyle, darkStyle string) ([]byte, error) {
	light := styles.Get(lightStyle)
	dark := styles.Get(darkStyle)
	if light.Name != lightStyle || dark.Name != darkStyle {
		return nil, errors.New(tagStyleMissing, "a chroma style is missing", "light", lightStyle, "dark", darkStyle)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "/* Generated by internal/markdown/cmd/gencodecss (go generate ./...); do not edit.\n"+
		"   The code blocks of internal/markdown: <pre class=\"code\" data-lang=\"go\"><code>…</code></pre>, with the\n"+
		"   tokens of a highlighted block in <span class=\"%s…\">. Light palette: chroma style %q; dark: %q.\n"+
		"   The dark palette applies as in app.css: data-theme=\"dark\", or the system's setting unless\n"+
		"   data-theme=\"light\". */\n\n", markdown.CodeClassPrefix, lightStyle, darkStyle)

	b.WriteString(blockCSS(lightPalette))
	b.WriteString("\n")
	b.WriteString(tokenCSS(light, nil, "", ""))

	b.WriteString("\n/* Dark: chosen in the settings. */\n")
	b.WriteString(darkVars(darkPalette, darkSelector, ""))
	b.WriteString(tokenCSS(dark, light, darkSelector+" ", ""))

	b.WriteString("\n/* Dark: the system's setting, unless Light was chosen. */\n")
	b.WriteString(darkMedia + " {\n")
	b.WriteString(darkVars(darkPalette, systemDarkSel, "  "))
	b.WriteString(tokenCSS(dark, light, systemDarkSel+" ", "  "))
	b.WriteString("}\n")
	return b.Bytes(), nil
}

// blockCSS returns the rules of the block: its custom properties for palette
// p (on :root) and its box.
func blockCSS(p palette) string {
	var b strings.Builder
	fmt.Fprintf(&b, ":root {\n  --code-bg: %s;\n  --code-fg: %s;\n  --code-border: %s;\n}\n\n", p.bg, p.fg, p.border)
	b.WriteString("pre.code {\n")
	b.WriteString("  margin: 0.75em 0;\n  padding: 0.75rem 1rem;\n  overflow-x: auto;\n")
	b.WriteString("  border: 1px solid var(--code-border);\n  border-radius: 6px;\n")
	b.WriteString("  background: var(--code-bg);\n  color: var(--code-fg);\n")
	b.WriteString("  font-family: var(--mono, ui-monospace, SFMono-Regular, Menlo, Consolas, monospace);\n")
	b.WriteString("  font-size: 0.875em;\n  line-height: 1.45;\n  tab-size: 4;\n}\n\n")
	b.WriteString("pre.code code {\n  font: inherit;\n  background: none;\n  padding: 0;\n}\n")
	return b.String()
}

// darkVars returns the rule that sets the custom properties of palette p for
// the elements matched by sel.
func darkVars(p palette, sel, indent string) string {
	return fmt.Sprintf("%s%s {\n%s  --code-bg: %s;\n%s  --code-fg: %s;\n%s  --code-border: %s;\n%s}\n",
		indent, sel, indent, p.bg, indent, p.fg, indent, p.border, indent)
}

// skippedTypes are the token types that are no tokens of code: the wrapping
// elements and the line numbers, which the renderer does not write.
var skippedTypes = map[chroma.TokenType]bool{
	chroma.Background: true, chroma.PreWrapper: true, chroma.Line: true, chroma.CodeLine: true,
	chroma.LineNumbers: true, chroma.LineNumbersTable: true, chroma.LineHighlight: true,
	chroma.LineTable: true, chroma.LineTableTD: true, chroma.LineLink: true,
}

// tokenEntries returns the style of each token class (with the prefix) that
// style sets, relative to the block's own text and background.
func tokenEntries(style *chroma.Style) map[string]chroma.StyleEntry {
	bg := style.Get(chroma.Background)
	entries := map[string]chroma.StyleEntry{}
	for tt, name := range chroma.StandardTypes {
		if name == "" || skippedTypes[tt] {
			continue
		}
		entries[markdown.CodeClassPrefix+name] = style.Get(tt).Sub(bg)
	}
	return entries
}

// tokenCSS returns the rules of the token classes of style, as
// "<prefix>.code .hl-k { color: …; }", sorted by class name. When ref is not
// nil the rules are for a palette that comes after ref in the cascade: each
// rule has what differs from the ref palette's rule of the class, and undoes
// what the ref palette sets and this one does not, so the two never mix.
func tokenCSS(style, ref *chroma.Style, prefix, indent string) string {
	entries := tokenEntries(style)
	var refEntries map[string]chroma.StyleEntry
	if ref != nil {
		refEntries = tokenEntries(ref)
	}
	classes := make([]string, 0, len(entries))
	for class := range entries {
		classes = append(classes, class)
	}
	slices.Sort(classes)
	var b strings.Builder
	for _, class := range classes {
		decls := declarations(entries[class], refEntries[class])
		if len(decls) == 0 {
			continue
		}
		fmt.Fprintf(&b, "%s%s.code .%s { %s; }\n", indent, prefix, class, strings.Join(decls, "; "))
	}
	return b.String()
}

// declarations returns the CSS declarations that give an element the style e
// when the cascade has ref for it: only what differs, and the neutral value
// for what ref sets and e does not.
func declarations(e, ref chroma.StyleEntry) []string {
	var d []string
	switch {
	case e.Colour.IsSet() && (!ref.Colour.IsSet() || e.Colour != ref.Colour):
		d = append(d, "color: "+e.Colour.String())
	case !e.Colour.IsSet() && ref.Colour.IsSet():
		d = append(d, "color: inherit")
	}
	switch {
	case e.Background.IsSet() && (!ref.Background.IsSet() || e.Background != ref.Background):
		d = append(d, "background-color: "+e.Background.String())
	case !e.Background.IsSet() && ref.Background.IsSet():
		d = append(d, "background-color: transparent")
	}
	if on := e.Bold == chroma.Yes; on != (ref.Bold == chroma.Yes) {
		d = append(d, "font-weight: "+map[bool]string{true: "bold", false: "normal"}[on])
	}
	if on := e.Italic == chroma.Yes; on != (ref.Italic == chroma.Yes) {
		d = append(d, "font-style: "+map[bool]string{true: "italic", false: "normal"}[on])
	}
	if on := e.Underline == chroma.Yes; on != (ref.Underline == chroma.Yes) {
		d = append(d, "text-decoration: "+map[bool]string{true: "underline", false: "none"}[on])
	}
	return d
}

// tagStyleMissing marks a chroma style that this program needs and the
// library does not have.
const tagStyleMissing = "CodeStyleMissing"
