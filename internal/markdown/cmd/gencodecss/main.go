// Command gencodecss writes internal/web/static/code.css, the stylesheet of
// the code blocks that internal/markdown renders: the block itself and the
// colour of each hl- class of the highlighted tokens. It is run by go generate
// (see internal/markdown/code.go) and its output is committed; a test fails
// when the committed file is out of date.
//
// The colours are not written here. Each token class takes the colour of the
// family it belongs to, as var(--code-keyword), var(--code-string) and so on,
// and app.css sets those custom properties for the light and the dark theme
// (SPEC D57), so the theme is chosen in one place and a block follows it with
// no rule of its own. Chroma's token types map to a family by their kind: every
// Keyword* to the keyword, every String* to the string, and so on (family).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/alecthomas/chroma/v2"

	"github.com/rm4n0s/clowder/internal/markdown"
)

func main() {
	out := flag.String("o", "", "the file to write")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "gencodecss: -o is required")
		os.Exit(2)
	}
	if err := os.WriteFile(*out, generate(), 0o644); err != nil { //nolint:gosec // a stylesheet that is committed
		fmt.Fprintln(os.Stderr, "gencodecss:", err)
		os.Exit(1)
	}
}

// generate returns the content of code.css: the rules of the block, then one
// rule for each token class that has a family.
func generate() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "/* Generated by internal/markdown/cmd/gencodecss (go generate ./...); do not edit.\n"+
		"   The code blocks of internal/markdown: <pre class=\"code\" data-lang=\"go\"><code>…</code></pre>, with the\n"+
		"   tokens of a highlighted block in <span class=\"%s…\">. Every colour is a custom property\n"+
		"   (--code-ground, --code-text, --code-keyword, …) that app.css sets for the light and the dark\n"+
		"   theme, so this file has no colour of its own. */\n\n", markdown.CodeClassPrefix)
	b.WriteString(blockCSS)
	b.WriteString("\n")
	b.WriteString(tokenCSS())
	return b.Bytes()
}

// blockCSS is the rules of the block: its box and the colours of its ground
// and of its plain text.
const blockCSS = `pre.code {
  margin: 0.75em 0;
  padding: 14px 16px;
  overflow-x: auto;
  border: 1px solid var(--code-border);
  border-radius: 14px;
  background: var(--code-ground);
  color: var(--code-text);
  font-family: var(--font-mono, ui-monospace, monospace);
  font-size: 13px;
  line-height: 1.6;
  tab-size: 4;
}

pre.code code {
  font: inherit;
  background: none;
  padding: 0;
}
`

// The families of tokens: each is the custom property --code-<family> of
// app.css.
const (
	familyKeyword     = "keyword"
	familyName        = "name"
	familyFunction    = "function"
	familyType        = "type"
	familyString      = "string"
	familyNumber      = "number"
	familyComment     = "comment"
	familyOperator    = "operator"
	familyPunctuation = "punctuation"
)

// family returns the family of the token type tt and whether the class is
// bold, italic or underlined, or "" when the type has no colour (the text, the
// white space and the wrappers of the renderer, which it does not write).
func family(tt chroma.TokenType) (fam string, extra []string) {
	switch {
	case tt == chroma.GenericStrong:
		return "", []string{"font-weight: bold"}
	case tt == chroma.GenericEmph:
		return "", []string{"font-style: italic"}
	case tt == chroma.GenericUnderline:
		return "", []string{"text-decoration: underline"}
	case tt == chroma.GenericHeading, tt == chroma.GenericSubheading:
		return familyFunction, []string{"font-weight: bold"}
	case tt == chroma.GenericInserted:
		return familyString, nil
	case tt == chroma.GenericDeleted, tt == chroma.GenericError, tt == chroma.GenericTraceback, tt == chroma.Error:
		return familyKeyword, nil
	case tt == chroma.GenericOutput, tt == chroma.GenericPrompt:
		return familyComment, nil
	case tt == chroma.KeywordType:
		return familyType, nil
	case tt.InCategory(chroma.Keyword):
		return familyKeyword, nil
	case tt == chroma.NameFunction, tt == chroma.NameFunctionMagic, tt == chroma.NameBuiltin, tt == chroma.NameBuiltinPseudo, tt == chroma.NameDecorator:
		return familyFunction, nil
	case tt == chroma.NameClass, tt == chroma.NameException, tt == chroma.NameNamespace, tt == chroma.NameAttribute:
		return familyType, nil
	case tt == chroma.NameTag:
		return familyKeyword, nil
	case tt == chroma.NameConstant:
		return familyNumber, nil
	case tt.InCategory(chroma.Name):
		return familyName, nil
	case tt.InSubCategory(chroma.LiteralString):
		return familyString, nil
	case tt.InSubCategory(chroma.LiteralNumber):
		return familyNumber, nil
	case tt.InCategory(chroma.Literal):
		return familyString, nil
	case tt == chroma.CommentPreproc, tt == chroma.CommentPreprocFile:
		return familyKeyword, nil
	case tt.InCategory(chroma.Comment):
		return familyComment, nil
	case tt == chroma.OperatorWord, tt == chroma.OperatorReserved:
		return familyKeyword, nil
	case tt.InCategory(chroma.Operator):
		return familyOperator, nil
	case tt.InCategory(chroma.Punctuation):
		return familyPunctuation, nil
	}
	return "", nil
}

// tokenCSS returns the rules of the token classes, as
// ".code .hl-k { color: var(--code-keyword); }", sorted by class name. A class
// of a type with no family and no weight or slant has no rule.
func tokenCSS() string {
	type rule struct{ class, decls string }
	var rules []rule
	for tt, name := range chroma.StandardTypes {
		if name == "" {
			continue
		}
		fam, extra := family(tt)
		var decls []string
		if fam != "" {
			decls = append(decls, "color: var(--code-"+fam+")")
		}
		decls = append(decls, extra...)
		if len(decls) == 0 {
			continue
		}
		rules = append(rules, rule{class: markdown.CodeClassPrefix + name, decls: strings.Join(decls, "; ")})
	}
	slices.SortFunc(rules, func(a, b rule) int { return strings.Compare(a.class, b.class) })
	var b strings.Builder
	for _, r := range rules {
		fmt.Fprintf(&b, ".code .%s { %s; }\n", r.class, r.decls)
	}
	return b.String()
}
